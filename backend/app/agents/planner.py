class PlannedFileModel(BaseModel):
    path: str = Field(description="Safe project-relative file path, e.g. 'main.py', 'cache.py', 'index.html', or 'static/styles.css'")
    responsibility: str = Field(description="Single, clear responsibility of this specific file")


class PlannerResult(BaseModel):
    project_summary: str = Field(description="Concise 1-3 sentence summary of the project derived from the PRD")
    required_features: List[str] = Field(description="List of specific features and functional requirements derived from the PRD")
    architecture_type: str = Field(description="Type of architecture: 'web_app', 'backend_api', 'cli_tool', or 'python_library'")
    tech_stack: List[str] = Field(description="Minimal list of libraries and technologies actually needed by the project")
    file_plan: List[PlannedFileModel] = Field(description="List of planned files with clear, separated responsibilities")
    acceptance_criteria: List[str] = Field(description="Concrete, verifiable acceptance criteria that QA can evaluate and test")
    requires_web: bool = Field(description="True ONLY if the PRD requests a web interface, browser UI, or HTML/frontend dashboard")
    is_fallback: bool = Field(default=False, description="True if generated by deterministic fallback rather than LLM")


PLANNER_SYSTEM_PROMPT = """You are TARA's Lead Software Architect and Planner.
Analyze the approved PRD and design a minimal, clean, and complete project plan.

Rules:
1. Derive requirements strictly from the PRD. Do not invent unrelated features or substitute generic templates.
2. Architecture & File Plan:
   - Choose the simplest architecture that satisfies the PRD.
   - Give each file a clear, single responsibility. Keep related code together and avoid monolithic single-file applications.
   - For web apps (PRD requests a web interface, dashboard, frontend, HTML/browser controls):
     Set requires_web = True. Include separate frontend files (index.html, static/styles.css, static/app.js) and Python backend files if backend behavior is needed.
   - For non-web projects (in-memory cache, CLI tool, algorithm, backend API only, Python library):
     Set requires_web = False. DO NOT force index.html or frontend files onto projects that do not need a web interface.
   - Use safe relative paths only. Reject absolute paths or paths with '..'.
3. Acceptance Criteria:
   - Provide concrete, testable criteria QA can check (e.g. specific function signatures, endpoints, error cases, UI elements).
   - If requires_web is True, include verification that the web preview loads and interactive controls function.
   - Include verification that syntax is valid and no TODO/placeholder markers exist.
4. Keep dependencies minimal; include only packages the project genuinely needs.

Return a valid JSON object matching the PlannerResult schema without markdown fences."""


def _detect_web_requirement(prd_text: str) -> bool:
    """Detects if the PRD specifies a web application, browser interface, or UI."""
    prd_lower = (prd_text or "").lower()
    web_keywords = [
        "web app", "web application", "website", "frontend", "html", "css",
        "browser preview", "web preview", "dashboard", "user interface", " ui ",
        "gui", "landing page", "web page", "web portal", "interactive view"
    ]
    # Check for direct web keywords
    for kw in web_keywords:
        if kw in prd_lower:
            return True
            
    # Check for UI interaction indicators
    ui_interaction_matches = re.search(r"\b(button|input field|dropdown|modal|form|click|render)\b", prd_lower)
    if ui_interaction_matches and ("page" in prd_lower or "view" in prd_lower or "screen" in prd_lower):
        return True
        
    return False


def generate_plan_fallback(
    prd_text: str,
    human_notes: str = "",
    ceo_critique: Optional[Dict[str, Any]] = None
) -> PlannerResult:
    """Deterministic fallback planner that extracts features and derives an appropriate architecture."""
    title_match = re.search(r"(?im)^\s*#\s+(.+)$", prd_text or "")
    title = (title_match.group(1).strip() if title_match else "Autonomous Service")[:80]
    
    # Extract requirements from bullet points or numbered lists
    requirements: List[str] = []
    for line in (prd_text or "").splitlines():
        cleaned = re.sub(r"^\s*(?:[-*+]\s+|\d+[.)]\s+)", "", line).strip()
        if cleaned and not line.lstrip().startswith("#") and len(cleaned) > 5:
            requirements.append(cleaned)
        if len(requirements) >= 8:
            break
            
    if not requirements:
        requirements = [f"Core functional requirements for {title}", "Robust error handling and input validation"]
        
    requires_web = _detect_web_requirement(prd_text)
    
    # Determine architecture and file plan based on web requirement
    if requires_web:
        architecture_type = "web_app"
        tech_stack = ["FastAPI", "Uvicorn", "HTML5", "CSS3", "JavaScript"]
        file_plan = [
            PlannedFileModel(
                path="index.html",
                responsibility=f"Semantic HTML5 interface and control layout for {title}"
            ),
            PlannedFileModel(
                path="static/styles.css",
                responsibility="Responsive, accessible styling, layout grids, and visual states"
            ),
            PlannedFileModel(
                path="static/app.js",
                responsibility="Client-side DOM events, state management, and API request handling"
            ),
            PlannedFileModel(
                path="main.py",
                responsibility="FastAPI application entrypoint, route endpoints, and static file serving"
            ),
            PlannedFileModel(
                path="models.py",
                responsibility="Pydantic domain models, request/response validation schemas"
            ),
            PlannedFileModel(
                path="utils.py",
                responsibility="Helper functions, logging configuration, and utilities"
            ),
        ]
        acceptance_criteria = [
            f"Web preview loads index.html with functional controls matching {title} requirements",
            "Referenced CSS (/static/styles.css) and JS (/static/app.js) files exist and load cleanly",
            "Interactive buttons and input controls trigger defined client or API actions without silent no-ops",
            "FastAPI backend endpoints validate inputs and return structured JSON responses",
            "All Python and JavaScript files are free of syntax errors and placeholder TODO markers",
        ]
    else:
        # Non-web project (e.g. backend service, cache, CLI tool, library)
        prd_lower = (prd_text or "").lower()
        if "cache" in prd_lower:
            architecture_type = "backend_service"
            tech_stack = ["Python 3.11", "Standard Library", "Typing"]
            file_plan = [
                PlannedFileModel(path="main.py", responsibility="Service entrypoint, CLI runner, and operational interface"),
                PlannedFileModel(path="cache.py", responsibility="Core in-memory cache implementation with TTL and eviction mechanisms"),
                PlannedFileModel(path="models.py", responsibility="Data models, cache entry definitions, and status structures"),
                PlannedFileModel(path="utils.py", responsibility="Time handling, cleanup background helpers, and logging"),
            ]
            acceptance_criteria = [
                "Cache correctly stores, retrieves, and updates key-value entries",
                "Expired entries are invalidated and evicted according to TTL",
                "Cleanup routine removes expired entries safely without concurrency errors",
                "Error handling catches invalid keys, expired lookups, and boundary conditions",
                "All Python files parse with valid syntax and contain no TODOs or placeholders",
            ]
        elif "order" in prd_lower or "microservice" in prd_lower:
            architecture_type = "backend_api"
            tech_stack = ["FastAPI", "Pydantic", "Uvicorn"]
            file_plan = [
                PlannedFileModel(path="main.py", responsibility="FastAPI app entrypoint, REST route handlers, and middleware"),
                PlannedFileModel(path="models.py", responsibility="Pydantic schemas for order requests, responses, and validation"),
                PlannedFileModel(path="service.py", responsibility="Order processing business logic and state transitions"),
                PlannedFileModel(path="utils.py", responsibility="Logging helpers, ID generation, and validation utilities"),
            ]
            acceptance_criteria = [
                "FastAPI routes handle order creation, retrieval, and status queries",
                "Pydantic models validate order payload fields and reject malformed requests",
                "Service logic correctly computes totals and enforces business rules",
                "All Python files parse cleanly with zero syntax errors or TODO markers",
            ]
        else:
            architecture_type = "python_library"
            tech_stack = ["Python 3.11", "Standard Library"]
            file_plan = [
                PlannedFileModel(path="main.py", responsibility="Application orchestration and demonstration entrypoint"),
                PlannedFileModel(path="core.py", responsibility=f"Core domain implementation satisfying {title}"),
                PlannedFileModel(path="models.py", responsibility="Data types, configuration structures, and validation"),
                PlannedFileModel(path="utils.py", responsibility="Helper routines, formatters, and error handling"),
            ]
            acceptance_criteria = [
                f"Core module implements primary features requested in {title}",
                "Entrypoint executes expected workflows and displays structured results",
                "All modules parse with valid syntax and pass import checks",
                "Code is modular with separated responsibilities and no TODO stubs",
            ]

    # Append criteria for specific extracted requirements
    for req in requirements[:3]:
        acceptance_criteria.append(f"Verify requirement is satisfied: {req[:90]}")

    summary = f"Planned {architecture_type} for '{title}' featuring {len(requirements)} core requirements organized across {len(file_plan)} dedicated files."
    
    return PlannerResult(
        project_summary=summary,
        required_features=requirements,
        architecture_type=architecture_type,
        tech_stack=tech_stack,
        file_plan=file_plan,
        acceptance_criteria=acceptance_criteria,
        requires_web=requires_web,
        is_fallback=True,
    )


def call_ollama_planner(
    prd_text: str,
    human_notes: str = "",
    ceo_critique: Optional[Dict[str, Any]] = None
) -> Optional[PlannerResult]:
    """Queries local model qwen2.5-coder:7b to generate a structured project plan."""
    url = "http://localhost:11434/v1/chat/completions"
    model_name = os.getenv("OLLAMA_MODEL", "qwen2.5-coder:7b")
    
    user_prompt = f"Approved PRD:\n{prd_text}\n"
    if human_notes:
        user_prompt += f"\nUser Feedback / Notes:\n{human_notes}\n"
    if ceo_critique:
        user_prompt += f"\nCEO Critique:\n{ceo_critique}\n"

    try:
        import httpx
        payload = {
            "model": model_name,
            "messages": [
                {"role": "system", "content": PLANNER_SYSTEM_PROMPT},
                {"role": "user", "content": user_prompt},
            ],
            "response_format": {"type": "json_object"},
            "temperature": 0.2,
        }
        # Use short connect timeout so tests/workflows don't hang if Ollama is offline
        timeout = httpx.Timeout(
            timeout=float(os.getenv("OLLAMA_PLANNER_TIMEOUT", "4.0")),
            connect=float(os.getenv("OLLAMA_CONNECT_TIMEOUT", "1.5"))
        )
        with httpx.Client(timeout=timeout) as http_client:
            resp = http_client.post(url, json=payload)
            if resp.status_code == 200:
                data = resp.json()
                content = data["choices"][0]["message"]["content"]
                parsed = PlannerResult.model_validate_json(content)
                parsed.is_fallback = False
                logger.info("Successfully generated project plan via local model %s", model_name)
                return parsed
    except Exception as exc:
        logger.debug("Local planner notice (%s). Proceeding with alternative provider.", exc)
    return None


def call_gemini_planner(
    prd_text: str,
    human_notes: str = "",
    ceo_critique: Optional[Dict[str, Any]] = None
) -> Optional[PlannerResult]:
    """Queries Google Gemini to generate a structured project plan."""
    global client
    api_key = settings.gemini_api_key or os.getenv("GEMINI_API_KEY", "")
    if client is None and api_key and api_key.startswith("AIzaSy"):
        try:
            from google import genai
            client = genai.Client(api_key=api_key)
        except Exception:
            client = None

    if client is None:
        return None

    try:
        from google.genai import types
        user_prompt = f"Approved PRD:\n{prd_text}\n"
        if human_notes:
            user_prompt += f"\nUser Feedback / Notes:\n{human_notes}\n"
        if ceo_critique:
            user_prompt += f"\nCEO Critique:\n{ceo_critique}\n"

        config = types.GenerateContentConfig(
            system_instruction=PLANNER_SYSTEM_PROMPT,
            response_mime_type="application/json",
            response_schema=PlannerResult,
            temperature=0.2,
        )
        response = call_gemini_with_fallback(
            client=client,
            contents=user_prompt,
            config=config,
            preferred_model=settings.default_model or "gemini-3.5-flash",
        )
        if response.parsed and isinstance(response.parsed, PlannerResult):
            response.parsed.is_fallback = False
            return response.parsed
        if response.text:
            parsed = PlannerResult.model_validate_json(response.text)
            parsed.is_fallback = False
            return parsed
    except Exception as exc:
        logger.warning("Gemini plan generation failed: %s", exc)
    return None


def generate_plan_from_prd(
    prd_text: str,
    human_notes: str = "",
    ceo_critique: Optional[Dict[str, Any]] = None
) -> PlannerResult:
    """Orchestrates plan generation across local model, cloud LLM, and deterministic fallback."""
    ollama_res = call_ollama_planner(prd_text, human_notes, ceo_critique)
    if ollama_res is not None:
        return ollama_res

    gemini_res = call_gemini_planner(prd_text, human_notes, ceo_critique)
    if gemini_res is not None:
        return gemini_res

    logger.info("Using deterministic PRD-derived fallback planner.")
    return generate_plan_fallback(prd_text, human_notes, ceo_critique)


def planner_node(state: AgentState) -> Dict[str, Any]:
    """LangGraph node executing project planning after user approval."""
    prd_text = state.get("prd_text", "")
    notes = state.get("human_feedback_notes", [])
    notes_str = "\n".join(notes) if notes else ""
    ceo_critique = state.get("ceo_critique")

    plan_result = generate_plan_from_prd(prd_text, notes_str, ceo_critique)

    # Convert to typed dict format matching AgentState
    plan_dict: PlannerOutput = {
        "project_summary": plan_result.project_summary,
        "required_features": plan_result.required_features,
        "architecture_type": plan_result.architecture_type,
        "tech_stack": plan_result.tech_stack,
        "file_plan": [{"path": f.path, "responsibility": f.responsibility} for f in plan_result.file_plan],
        "acceptance_criteria": plan_result.acceptance_criteria,
        "requires_web": plan_result.requires_web,
        "is_fallback": plan_result.is_fallback,
    }

    planned_files_str = ", ".join(f.path for f in plan_result.file_plan)
    log_msg = (
        f"Architecture Plan Created: {plan_result.architecture_type.upper()} "
        f"({len(plan_result.required_features)} features, {len(plan_result.file_plan)} files: {planned_files_str})"
    )

    log_entry = {
        "agent": "Planner",
        "stage": "planning",
        "message": log_msg,
        "timestamp": datetime.datetime.now(datetime.timezone.utc).isoformat(),
        "requires_web": plan_result.requires_web,
        "files": [f.path for f in plan_result.file_plan],
    }

    return {
        "plan": plan_dict,
        "current_stage": "plan_created",
        "logs": [log_entry],
    }
