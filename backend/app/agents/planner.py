class PlannedFileModel(BaseModel):
    path: str = Field(description="Safe project-relative file path, e.g. 'main.py', 'cache.py', 'frontend/index.html', or 'frontend/styles.css'")
    purpose: str = Field(default="", description="Clear purpose and responsibility of this specific file")
    responsibility: str = Field(default="", description="Backward-compatible alias for purpose")

    def model_post_init(self, __context: Any) -> None:
        if not self.purpose and self.responsibility:
            self.purpose = self.responsibility
        elif not self.responsibility and self.purpose:
            self.responsibility = self.purpose


class PlannerResult(BaseModel):
    app_summary: str = Field(default="", description="Concise 1-2 sentence app summary derived from the PRD")
    feature_list: List[str] = Field(default_factory=list, description="List of specific features and functional requirements derived from the PRD")
    proposed_files: List[PlannedFileModel] = Field(default_factory=list, description="List of planned files with each file's specific purpose")
    implementation_order: List[str] = Field(default_factory=list, description="Ordered sequence of file paths for implementation (e.g. data models -> utilities -> domain logic -> frontend/entrypoint)")
    # Backward-compatible fields
    project_summary: str = Field(default="", description="Concise 1-3 sentence summary of the project derived from the PRD")
    required_features: List[str] = Field(default_factory=list, description="List of specific features and functional requirements derived from the PRD")
    architecture_type: str = Field(default="web_app", description="Type of architecture: 'web_app', 'backend_api', 'cli_tool', or 'python_library'")
    tech_stack: List[str] = Field(default_factory=list, description="Minimal list of libraries and technologies actually needed by the project")
    file_plan: List[PlannedFileModel] = Field(default_factory=list, description="List of planned files with clear, separated responsibilities")
    acceptance_criteria: List[str] = Field(default_factory=list, description="Concrete, verifiable acceptance criteria that QA can evaluate and test")
    requires_web: bool = Field(default=False, description="True ONLY if the PRD requests a web interface, browser UI, or HTML/frontend dashboard")
    selected_skills: List[str] = Field(default_factory=list, description="Trusted skills selected for this project: web-frontend, fastapi, database, testing")
    is_fallback: bool = Field(default=False, description="True if generated by deterministic fallback rather than LLM")

    def model_post_init(self, __context: Any) -> None:
        if not self.app_summary and self.project_summary:
            self.app_summary = self.project_summary
        elif not self.project_summary and self.app_summary:
            self.project_summary = self.app_summary

        if not self.feature_list and self.required_features:
            self.feature_list = list(self.required_features)
        elif not self.required_features and self.feature_list:
            self.required_features = list(self.feature_list)

        if not self.proposed_files and self.file_plan:
            self.proposed_files = list(self.file_plan)
        elif not self.file_plan and self.proposed_files:
            self.file_plan = list(self.proposed_files)

        if not self.implementation_order and self.proposed_files:
            self.implementation_order = [f.path for f in self.proposed_files]


PLANNER_SYSTEM_PROMPT = """You are TARA's Lead Software Architect and Planner.
Analyze the approved PRD and design a minimal, clean, and complete project plan.

You must provide:
1. app_summary: A concise 1-2 sentence app summary.
2. feature_list: A concrete list of required features extracted from the PRD.
3. proposed_files: A list of separate, appropriately named files. Each file must have a safe relative path and a distinct purpose.
4. implementation_order: An ordered sequence of file paths specifying the build order (foundational data models and utilities first, followed by business/domain logic, followed by client/entrypoint).
5. acceptance_criteria: Concrete criteria for QA to verify.

Rules:
1. Derive requirements strictly from the PRD. Do not invent unrelated features or substitute generic templates.
2. Architecture & File Plan:
   - Choose the simplest architecture that satisfies the PRD.
   - Give each file a clear, single responsibility. Keep related code together and avoid monolithic single-file applications.
   - For web apps (PRD requests a web interface, dashboard, frontend, HTML/browser controls):
     Set requires_web = True. Include separate frontend files (frontend/index.html, frontend/styles.css, frontend/app.js) and Python backend files if backend behavior is needed.
   - For non-web projects (in-memory cache, CLI tool, algorithm, backend API only, Python library):
     Set requires_web = False. DO NOT force index.html or frontend files onto projects that do not need a web interface.
   - Use safe relative paths only. Reject absolute paths or paths with '..'.
3. Skill Selection:
   - Select trusted engineering skills from: ["web-frontend", "fastapi", "database", "testing"].
   - Include 'web-frontend' if requires_web is True.
   - Include 'fastapi' for REST APIs or web backend servers.
   - Include 'database' for data modeling, CRUD, caching, or persistence.
   - Include 'testing' for test generation, assertions, and QA verification.
4. Keep dependencies minimal; include only packages the project genuinely needs.

Return a valid JSON object matching the PlannerResult schema without markdown fences."""


def _detect_web_requirement(prd_text: str) -> bool:
    """Detects if the PRD specifies a web application, browser interface, or UI."""
    prd_lower = (prd_text or "").lower()
    web_keywords = [
        "web app", "web application", "website", "frontend", "html", "css",
        "browser preview", "web preview", "dashboard", "user interface", " ui ",
        "gui", "landing page", "web page", "web portal", "interactive view"
    ]
    # Check for direct web keywords
    for kw in web_keywords:
        if kw in prd_lower:
            return True
            
    # Check for UI interaction indicators
    ui_interaction_matches = re.search(r"\b(button|input field|dropdown|modal|form|click|render)\b", prd_lower)
    if ui_interaction_matches and ("page" in prd_lower or "view" in prd_lower or "screen" in prd_lower):
        return True
        
    return False


