def call_ollama_planner(
    prd_text: str,
    human_notes: str = "",
    ceo_critique: Optional[Dict[str, Any]] = None
) -> Optional[PlannerResult]:
    """Queries local model qwen2.5-coder:7b to generate a structured project plan."""
    url = "http://localhost:11434/v1/chat/completions"
    model_name = os.getenv("OLLAMA_MODEL", "qwen2.5-coder:7b")
    
    user_prompt = f"Approved PRD:\n{prd_text}\n"
    if human_notes:
        user_prompt += f"\nUser Feedback / Notes:\n{human_notes}\n"
    if ceo_critique:
        user_prompt += f"\nCEO Critique:\n{ceo_critique}\n"

    try:
        import httpx
        payload = {
            "model": model_name,
            "messages": [
                {"role": "system", "content": PLANNER_SYSTEM_PROMPT},
                {"role": "user", "content": user_prompt},
            ],
            "response_format": {"type": "json_object"},
            "temperature": 0.2,
        }
        # Use short connect timeout so tests/workflows don't hang if Ollama is offline
        timeout = httpx.Timeout(
            timeout=float(os.getenv("OLLAMA_PLANNER_TIMEOUT", "4.0")),
            connect=float(os.getenv("OLLAMA_CONNECT_TIMEOUT", "1.5"))
        )
        with httpx.Client(timeout=timeout) as http_client:
            resp = http_client.post(url, json=payload)
            if resp.status_code == 200:
                data = resp.json()
                content = data["choices"][0]["message"]["content"]
                parsed = PlannerResult.model_validate_json(content)
                parsed.is_fallback = False
                logger.info("Successfully generated project plan via local model %s", model_name)
                return parsed
    except Exception as exc:
        logger.debug("Local planner notice (%s). Proceeding with alternative provider.", exc)
    return None


def call_gemini_planner(
    prd_text: str,
    human_notes: str = "",
    ceo_critique: Optional[Dict[str, Any]] = None
) -> Optional[PlannerResult]:
    """Queries Google Gemini to generate a structured project plan."""
    global client
    api_key = settings.gemini_api_key or os.getenv("GEMINI_API_KEY", "")
    if client is None and api_key and api_key.startswith("AIzaSy"):
        try:
            from google import genai
            client = genai.Client(api_key=api_key)
        except Exception:
            client = None

    if client is None:
        return None

    try:
        from google.genai import types
        user_prompt = f"Approved PRD:\n{prd_text}\n"
        if human_notes:
            user_prompt += f"\nUser Feedback / Notes:\n{human_notes}\n"
        if ceo_critique:
            user_prompt += f"\nCEO Critique:\n{ceo_critique}\n"

        config = types.GenerateContentConfig(
            system_instruction=PLANNER_SYSTEM_PROMPT,
            response_mime_type="application/json",
            response_schema=PlannerResult,
            temperature=0.2,
        )
        response = call_gemini_with_fallback(
            client=client,
            contents=user_prompt,
            config=config,
            preferred_model=settings.default_model or "gemini-3.5-flash",
        )
        if response.parsed and isinstance(response.parsed, PlannerResult):
            response.parsed.is_fallback = False
            return response.parsed
        if response.text:
            parsed = PlannerResult.model_validate_json(response.text)
            parsed.is_fallback = False
            return parsed
    except Exception as exc:
        logger.warning("Gemini plan generation failed: %s", exc)
    return None


def generate_plan_from_prd(
    prd_text: str,
    human_notes: str = "",
    ceo_critique: Optional[Dict[str, Any]] = None
) -> PlannerResult:
    """Orchestrates plan generation across local model, cloud LLM, and deterministic fallback."""
    ollama_res = call_ollama_planner(prd_text, human_notes, ceo_critique)
    if ollama_res is not None:
        return ollama_res

    gemini_res = call_gemini_planner(prd_text, human_notes, ceo_critique)
    if gemini_res is not None:
        return gemini_res

    logger.info("Using deterministic PRD-derived fallback planner.")
    return generate_plan_fallback(prd_text, human_notes, ceo_critique)


def planner_node(state: AgentState) -> Dict[str, Any]:
    """LangGraph node executing project planning after user approval."""
    prd_text = state.get("prd_text", "")
    notes = state.get("human_feedback_notes", [])
    notes_str = "\n".join(notes) if notes else ""
    ceo_critique = state.get("ceo_critique")

    plan_result = generate_plan_from_prd(prd_text, notes_str, ceo_critique)

    raw_files = plan_result.proposed_files or plan_result.file_plan or []
    normalized_files = [
        {
            "path": f.path,
            "purpose": f.purpose or f.responsibility or "Project module",
            "responsibility": f.responsibility or f.purpose or "Project module"
        }
        for f in raw_files
    ]
    order = plan_result.implementation_order or [f.path for f in raw_files]

    # Convert to typed dict format matching AgentState
    plan_dict: PlannerOutput = {
        "app_summary": plan_result.app_summary or plan_result.project_summary,
        "feature_list": plan_result.feature_list or plan_result.required_features,
        "proposed_files": normalized_files,
        "implementation_order": order,
        "project_summary": plan_result.app_summary or plan_result.project_summary,
        "required_features": plan_result.feature_list or plan_result.required_features,
        "architecture_type": plan_result.architecture_type,
        "tech_stack": plan_result.tech_stack,
        "file_plan": normalized_files,
        "acceptance_criteria": plan_result.acceptance_criteria,
        "requires_web": plan_result.requires_web,
        "selected_skills": plan_result.selected_skills,
        "is_fallback": plan_result.is_fallback,
    }

    planned_files_str = ", ".join(f["path"] for f in normalized_files)
    order_str = " -> ".join(order) if order else planned_files_str
    skills_str = ", ".join(plan_result.selected_skills) if plan_result.selected_skills else "none"
    log_msg = (
        f"Architecture Plan Created: {plan_result.architecture_type.upper()} "
        f"({len(plan_dict['feature_list'])} features, {len(normalized_files)} files: {planned_files_str}, "
        f"Order: [{order_str}], Skills: [{skills_str}])"
    )

    log_entry = {
        "agent": "Planner",
        "stage": "planning",
        "message": log_msg,
        "timestamp": datetime.datetime.now(datetime.timezone.utc).isoformat(),
        "requires_web": plan_result.requires_web,
        "selected_skills": plan_result.selected_skills,
        "files": [f.path for f in plan_result.file_plan],
    }

    return {
        "plan": plan_dict,
        "selected_skills": plan_result.selected_skills,
        "current_stage": "plan_created",
        "logs": [log_entry],
    }
